import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const projectRoot = dirname(dirname(scriptDir));
const assetDir = join(projectRoot, 'ui-preview', 'assets', 'device');
const headerPath = join(projectRoot, 'include', 'ui_assets.h');
const sourcePath = join(projectRoot, 'src', 'ui_assets.cpp');
const states = ['connecting', 'ready', 'recording', 'transcribing', 'result', 'error'];

function formatBytes(bytes) {
  const rows = [];
  for (let offset = 0; offset < bytes.length; offset += 12) {
    const values = [...bytes.subarray(offset, offset + 12)]
      .map((value) => `0x${value.toString(16).padStart(2, '0')}`)
      .join(', ');
    rows.push(`    ${values},`);
  }
  return rows.join('\n');
}

const header = `// Generated by ui-preview/scripts/embed-device-assets.mjs. Do not edit manually.
#pragma once

#if defined(WALKIE_UI_DEMO)

#include "audio_loop.h"

#include <cstddef>
#include <cstdint>

namespace stopwatch {

struct UiAsset {
    const uint8_t* data;
    size_t size;
};

UiAsset uiAssetFor(DeviceState state);

}  // namespace stopwatch

#endif
`;

const definitions = states.map((name) => {
  const bytes = readFileSync(join(assetDir, `${name}.png`));
  const symbol = `k${name[0].toUpperCase()}${name.slice(1)}Png`;
  return `alignas(4) const uint8_t ${symbol}[] PROGMEM = {\n${formatBytes(bytes)}\n};`;
});

const cases = states.map((name) => {
  const enumName = `${name[0].toUpperCase()}${name.slice(1)}`;
  const symbol = `k${enumName}Png`;
  return `        case DeviceState::${enumName}:\n            return {${symbol}, sizeof(${symbol})};`;
});

const source = `// Generated by ui-preview/scripts/embed-device-assets.mjs. Do not edit manually.
#include "ui_assets.h"

#if defined(WALKIE_UI_DEMO)

#include <Arduino.h>

namespace stopwatch {
namespace {

${definitions.join('\n\n')}

}  // namespace

UiAsset uiAssetFor(DeviceState state)
{
    switch (state) {
${cases.join('\n')}
    }
    return {nullptr, 0};
}

}  // namespace stopwatch

#endif
`;

mkdirSync(dirname(headerPath), { recursive: true });
mkdirSync(dirname(sourcePath), { recursive: true });
writeFileSync(headerPath, header);
writeFileSync(sourcePath, source);

console.log(`Generated ${relative(projectRoot, headerPath)} and ${relative(projectRoot, sourcePath)}`);
